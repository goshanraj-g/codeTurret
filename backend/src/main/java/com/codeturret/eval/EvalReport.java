package com.codeturret.eval;

import java.util.*;

/** Accumulates evaluation results and renders them as Markdown. */
final class EvalReport {

    private record Row(Benchmark benchmark, int repoLines, String selector, List<CandidateEvaluator.Result> results, long millis) {}

    private final int[] budgets;
    private final List<Row> rows = new ArrayList<>();

    EvalReport(int[] budgets) {
        this.budgets = budgets;
    }

    void add(Benchmark b, int repoLines, String selector, List<CandidateEvaluator.Result> results, long millis) {
        rows.add(new Row(b, repoLines, selector, results, millis));
    }

    String toMarkdown() {
        StringBuilder md = new StringBuilder();
        md.append("# Candidate selection benchmark\n\n")
          .append("Share of labelled vulnerabilities whose code is sent to the LLM when each selector's candidates are ")
          .append("taken in priority order until the line budget is spent. `@all` means no budget: for selectors that ")
          .append("rank every unit, that is the whole repo, so compare selectors at fixed budgets. ")
          .append("Generated by `EvalRunner`; do not edit by hand.\n\n");

        md.append("## Overall (all benchmarks)\n\n");
        header(md);
        Map<String, List<Row>> bySelector = new LinkedHashMap<>();
        for (Row r : rows) bySelector.computeIfAbsent(r.selector(), k -> new ArrayList<>()).add(r);
        for (var e : bySelector.entrySet()) {
            int total = e.getValue().stream().mapToInt(r -> r.benchmark().vulns().size()).sum();
            md.append("| ").append(e.getKey());
            for (int i = 0; i < budgets.length; i++) {
                final int idx = i;
                int covered = e.getValue().stream().mapToInt(r -> r.results().get(idx).coveredVulnIds().size()).sum();
                md.append(" | ").append(pct(covered, total));
            }
            int lines = e.getValue().stream().mapToInt(r -> last(r).linesSent()).sum();
            long ms = e.getValue().stream().mapToLong(Row::millis).sum();
            md.append(" | ").append(lines).append(" | ").append(ms).append(" |\n");
        }

        Map<String, List<Row>> byBenchmark = new LinkedHashMap<>();
        for (Row r : rows) byBenchmark.computeIfAbsent(r.benchmark().name(), k -> new ArrayList<>()).add(r);
        for (var e : byBenchmark.entrySet()) {
            Benchmark b = e.getValue().get(0).benchmark();
            md.append("\n## ").append(b.name()).append(" (").append(b.vulns().size()).append(" vulns, ")
              .append(e.getValue().get(0).repoLines()).append(" lines of code)\n\n");
            header(md);
            for (Row r : e.getValue()) {
                md.append("| ").append(r.selector());
                for (CandidateEvaluator.Result res : r.results()) {
                    md.append(" | ").append(pct(res.coveredVulnIds().size(), b.vulns().size()));
                }
                md.append(" | ").append(last(r).linesSent()).append(" | ").append(r.millis()).append(" |\n");
            }
            md.append("\n<details><summary>Missed at unlimited budget</summary>\n\n");
            for (Row r : e.getValue()) {
                Set<String> hit = new HashSet<>(last(r).coveredVulnIds());
                List<String> missed = b.vulns().stream().map(Benchmark.Vuln::id).filter(id -> !hit.contains(id)).toList();
                md.append("- **").append(r.selector()).append("**: ")
                  .append(missed.isEmpty() ? "none" : String.join(", ", missed)).append("\n");
            }
            md.append("\n</details>\n");
        }
        return md.toString();
    }

    private void header(StringBuilder md) {
        md.append("| Selector");
        for (int b : budgets) md.append(" | @").append(b == CandidateEvaluator.UNLIMITED ? "all" : String.valueOf(b));
        md.append(" | Lines sent (all) | Select ms |\n|---");
        for (int ignored : budgets) md.append("|---:");
        md.append("|---:|---:|\n");
    }

    private static CandidateEvaluator.Result last(Row r) {
        return r.results().get(r.results().size() - 1);
    }

    private static String pct(int n, int d) {
        return d == 0 ? "n/a" : String.format("%d%% (%d/%d)", Math.round(100.0 * n / d), n, d);
    }
}
